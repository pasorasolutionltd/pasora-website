/* ──────────────────────────────────────────────────────────────
 *  ROUTING
 * ────────────────────────────────────────────────────────────── */
$action    = $_GET['action'] ?? '';
$needsSetup = empty($config['password_hash']);

/* Logout */
if ($action === 'logout') {
    $_SESSION = [];
    session_destroy();
    header('Location: index.php');
    exit;
}

/* ── First-run setup: create the admin password ───────────────── */
if ($needsSetup) {
    $err = '';
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        if (!csrf_ok()) {
            $err = 'Session expired, please try again.';
        } else {
            $p1 = (string) ($_POST['pw'] ?? '');
            $p2 = (string) ($_POST['pw2'] ?? '');
            if (strlen($p1) < 10) {
                $err = 'Use a password of at least 10 characters.';
            } elseif ($p1 !== $p2) {
                $err = 'The two passwords do not match.';
            } else {
                $config['password_hash'] = password_hash($p1, PASSWORD_DEFAULT);
                if (save_config($config, $configFile)) {
                    $_SESSION['authed'] = true;
                    session_regenerate_id(true);
                    deploy_log('Admin password created.');
                    header('Location: index.php');
                    exit;
                }
                $err = 'Could not write admin/config.local.php. Make the admin folder '
                     . 'writable, or create the file manually from config.example.php.';
            }
        }
    }
    page_top('Set up', $config['site_name']);
    echo '<div class="card"><h1>Create your admin password</h1>';
    echo '<p>This is the first run. Choose a password to protect the deploy panel. '
       . 'It is stored only as a one-way hash in <code>admin/config.local.php</code>.</p>';
    if ($err) { echo '<div class="note err">' . h($err) . '</div>'; }
    echo '<form method="post" action="index.php">';
    echo '<input type="hidden" name="csrf" value="' . h(csrf_token()) . '">';
    echo '<label for="pw">New password (min 10 characters)</label>';
    echo '<input id="pw" type="password" name="pw" autocomplete="new-password" required minlength="10">';
    echo '<label for="pw2">Confirm password</label>';
    echo '<input id="pw2" type="password" name="pw2" autocomplete="new-password" required minlength="10">';
    echo '<button type="submit">Create password &amp; sign in</button>';
    echo '</form></div>';
    echo '<p class="muted">Tip: set this immediately after your first deploy so the panel is never left open.</p>';
    page_bottom();
    exit;
}

/* ── Login ────────────────────────────────────────────────────── */
if (!is_authed()) {
    $err       = '';
    $lockUntil = (int) ($_SESSION['lock_until'] ?? 0);
    $locked    = $lockUntil > time();

    if ($_SERVER['REQUEST_METHOD'] === 'POST' && !$locked) {
        if (!csrf_ok()) {
            $err = 'Session expired, please try again.';
        } elseif (password_verify((string) ($_POST['pw'] ?? ''), (string) $config['password_hash'])) {
            $_SESSION['authed']     = true;
            $_SESSION['login_fails'] = 0;
            session_regenerate_id(true);
            header('Location: index.php');
            exit;
        } else {
            $_SESSION['login_fails'] = (int) ($_SESSION['login_fails'] ?? 0) + 1;
            if ($_SESSION['login_fails'] >= 5) {
                $_SESSION['lock_until']  = time() + (int) $config['lockout_seconds'];
                $_SESSION['login_fails'] = 0;
                $locked = true;
                deploy_log('Login locked after repeated failures.');
            }
            $err = 'Incorrect password.';
        }
    }

    page_top('Sign in', $config['site_name']);
    echo '<div class="card"><h1>Sign in</h1>';
    if ($locked) {
        $mins = (int) ceil(((int) $_SESSION['lock_until'] - time()) / 60);
        echo '<div class="note err">Too many attempts. Try again in about ' . $mins . ' minute(s).</div>';
    }
    if ($err && !$locked) { echo '<div class="note err">' . h($err) . '</div>'; }
    echo '<form method="post" action="index.php">';
    echo '<input type="hidden" name="csrf" value="' . h(csrf_token()) . '">';
    echo '<label for="pw">Admin password</label>';
    echo '<input id="pw" type="password" name="pw" autocomplete="current-password" required'
       . ($locked ? ' disabled' : '') . '>';
    echo '<button type="submit"' . ($locked ? ' disabled' : '') . '>Sign in</button>';
    echo '</form></div>';
    page_bottom();
    exit;
}

/* ── Authenticated: handle a deploy POST ──────────────────────── */
$flash = null;
if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['do'] ?? '') === 'deploy') {
    if (!csrf_ok()) {
        $flash = [false, 'Session expired, please try again.'];
    } else {
        [$ok, $msg] = run_deploy($config);
        deploy_log(($ok ? 'OK' : 'FAIL') . ': ' . $msg);
        $flash = [$ok, $msg];
    }
}

/* ── Settings: configure how "Deploy now" publishes ───────────── */
if ($action === 'settings') {
    $saved = false;
    $err   = '';
    if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['do'] ?? '') === 'savesettings') {
        if (!csrf_ok()) {
            $err = 'Session expired, please try again.';
        } else {
            $mode = (($_POST['deploy_mode'] ?? 'webhook') === 'git') ? 'git' : 'webhook';
            $url  = trim((string) ($_POST['deploy_hook_url'] ?? ''));
            $gp   = trim((string) ($_POST['git_path'] ?? '')) ?: dirname(__DIR__);
            if ($mode === 'webhook' && $url !== '' && !preg_match('~^https?://~i', $url)) {
                $err = 'The deploy URL should start with http:// or https://';
            } else {
                $config['deploy_mode']     = $mode;
                $config['deploy_hook_url'] = $url;
                $config['git_path']        = $gp;
                if (save_config($config, $configFile)) {
                    deploy_log('Settings updated (mode=' . $mode . ').');
                    $saved = true;
                } else {
                    $err = 'Could not write admin/config.local.php (check folder permissions).';
                }
            }
        }
    }

    $mode = $config['deploy_mode'] ?? 'webhook';
    app_top('settings', 'Settings', $config['site_name'], 'How the site publishes to the server');
    echo '<p>Tell the panel how the <b>Deploy now</b> button should publish your site.</p>';
    if ($saved) { echo '<div class="note ok">&#10003; Settings saved.</div>'; }
    if ($err)   { echo '<div class="note err">' . h($err) . '</div>'; }

    echo '<div class="card"><form method="post" action="index.php?action=settings">';
    echo '<input type="hidden" name="csrf" value="' . h(csrf_token()) . '">';
    echo '<input type="hidden" name="do" value="savesettings">';
    echo '<label for="dm">Deploy method</label>';
    echo '<select id="dm" name="deploy_mode">';
    echo '<option value="webhook"' . ($mode === 'webhook' ? ' selected' : '') . '>Webhook (send a POST to a deploy URL, no SSH)</option>';
    echo '<option value="git"' . ($mode === 'git' ? ' selected' : '') . '>Git (run git pull on the server)</option>';
    echo '</select>';
    echo '<label for="url">Deploy webhook URL <span class="muted">(webhook mode. Paste it from hPanel, Git, auto-deployment)</span></label>';
    echo '<input id="url" type="text" name="deploy_hook_url" value="' . h((string) ($config['deploy_hook_url'] ?? '')) . '" placeholder="https://...">';
    echo '<label for="gp">Git path <span class="muted">(git mode only)</span></label>';
    echo '<input id="gp" type="text" name="git_path" value="' . h((string) ($config['git_path'] ?? dirname(__DIR__))) . '">';
    echo '<button type="submit">Save settings</button>';
    echo '</form></div>';
    app_bottom();
    exit;
}

/* ── Content: edit the public site's text, logo & social links ── */
if ($action === 'content') {
    require __DIR__ . '/../content.php';   // sets $SCHEMA and $C (live values)
    $saved = false;
    $err   = '';

    if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['do'] ?? '') === 'savecontent') {
        if (!csrf_ok()) {
            $err = 'Session expired, please try again.';
        } else {
            $posted = (array) ($_POST['f'] ?? []);
            $values = [];
            foreach ($SCHEMA as $group) {
                foreach ($group['fields'] as $key => $def) {
                    $values[$key] = trim((string) ($posted[$key] ?? ($C[$key] ?? '')));
                }
            }
            if (!empty($_FILES['logo_file']['name']) && is_uploaded_file((string) $_FILES['logo_file']['tmp_name'])) {
                [$ok, $res] = handle_logo_upload($_FILES['logo_file']);
                if ($ok) {
                    $values['logo'] = $res;
                } else {
                    $err = $res;
                }
            }
            if ($err === '') {
                $json = json_encode($values, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
                if (@file_put_contents(__DIR__ . '/content.local.json', $json, LOCK_EX) !== false) {
                    deploy_log('Content updated.');
                    $C     = array_merge($C, $values);
                    $saved = true;
                } else {
                    $err = 'Could not write admin/content.local.json (check folder permissions).';
                }
            }
        }
    }

    $viewBtn = '<a class="btn ghost sm" href="/" target="_blank" rel="noopener">' . icon('view') . 'View site</a>';
    app_top('content', 'Content', $config['site_name'], 'Update your site text, images and links. Changes publish instantly.', $viewBtn);
    if ($saved) { echo '<div class="note ok">&#10003; Saved. <a href="/" target="_blank" rel="noopener">View the site &rarr;</a></div>'; }
    if ($err)   { echo '<div class="note err">' . h($err) . '</div>'; }

    echo '<div class="secnav">';
    foreach ($SCHEMA as $gkey => $group) {
        echo '<a href="#grp-' . h($gkey) . '">' . h($group['label']) . '</a>';
    }
    echo '</div>';

    echo '<form method="post" action="index.php?action=content" enctype="multipart/form-data">';
    echo '<input type="hidden" name="csrf" value="' . h(csrf_token()) . '">';
    echo '<input type="hidden" name="do" value="savecontent">';
    foreach ($SCHEMA as $gkey => $group) {
        echo '<div class="card" id="grp-' . h($gkey) . '"><h2>' . h($group['label']) . '</h2>';
        foreach ($group['fields'] as $key => $def) {
            $label = (string) $def[0];
            $type  = (string) $def[1];
            $cur   = (string) ($C[$key] ?? $def[2]);
            $id    = 'f_' . $key;
            echo '<label for="' . h($id) . '">' . h($label) . '</label>';
            if ($type === 'image') {
                if ($cur !== '') {
                    echo '<div style="margin-bottom:10px"><img src="/' . h(ltrim($cur, '/')) . '" alt="current logo" '
                       . 'style="max-height:60px;max-width:220px;background:#0b1230;border:1px solid var(--line);border-radius:8px;padding:6px"></div>';
                }
                echo '<input type="hidden" name="f[' . h($key) . ']" value="' . h($cur) . '">';
                echo '<input id="' . h($id) . '" type="file" name="logo_file" accept="image/png,image/jpeg,image/webp,image/gif,image/svg+xml">';
                echo '<p class="muted" style="margin-top:-8px">PNG, JPG, SVG, WebP or GIF, max 2 MB. Leave empty to keep the current logo.</p>';
            } elseif ($type === 'textarea' || $type === 'list') {
                echo '<textarea id="' . h($id) . '" name="f[' . h($key) . ']" rows="' . ($type === 'list' ? 2 : 3) . '">' . h($cur) . '</textarea>';
            } else {
                echo '<input id="' . h($id) . '" type="text" name="f[' . h($key) . ']" value="' . h($cur) . '">';
            }
        }
        echo '</div>';
    }
    echo '<div class="savebar"><button type="submit">Save changes</button>'
       . '<span class="muted">Saved changes appear on the site right away.</span></div>';
    echo '</form>';
    app_bottom();
    exit;
}

