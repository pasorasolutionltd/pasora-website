/* ── Helpers ──────────────────────────────────────────────────── */
function save_config(array $cfg, string $file): bool
{
    $php = "<?php\n// Generated by the Pasora admin. Do NOT commit this file.\nreturn "
         . var_export($cfg, true) . ";\n";
    return (bool) @file_put_contents($file, $php, LOCK_EX);
}

function csrf_token(): string
{
    if (empty($_SESSION['csrf'])) {
        $_SESSION['csrf'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf'];
}

function csrf_ok(): bool
{
    return isset($_POST['csrf'], $_SESSION['csrf'])
        && hash_equals($_SESSION['csrf'], (string) $_POST['csrf']);
}

function is_authed(): bool
{
    return !empty($_SESSION['authed']);
}

function shell_available(): bool
{
    if (!function_exists('shell_exec')) {
        return false;
    }
    $disabled = array_map('trim', explode(',', (string) ini_get('disable_functions')));
    return !in_array('shell_exec', $disabled, true);
}

function current_commit(string $path): ?string
{
    if (!shell_available() || !is_dir($path . '/.git')) {
        return null;
    }
    $out = @shell_exec('cd ' . escapeshellarg($path)
        . ' 2>&1 && git log -1 --pretty=format:%h%x20%x2D%x20%s 2>&1');
    $out = trim((string) $out);
    return ($out === '' || stripos($out, 'fatal') !== false) ? null : $out;
}

/** Latest commit on GitHub's main branch (best-effort; null on any failure). */
function latest_github_commit(string $repo): ?array
{
    $repo = trim($repo);
    if ($repo === '' || !preg_match('~^[\w.-]+/[\w.-]+$~', $repo)) {
        return null;
    }
    $url  = "https://api.github.com/repos/$repo/commits/main";
    $json = false;
    if (function_exists('curl_init')) {
        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT        => 8,
            CURLOPT_HTTPHEADER     => ['User-Agent: Pasora-Admin', 'Accept: application/vnd.github+json'],
        ]);
        $json = curl_exec($ch);
        curl_close($ch);
    } else {
        $ctx = stream_context_create(['http' => [
            'header'        => "User-Agent: Pasora-Admin\r\nAccept: application/vnd.github+json\r\n",
            'timeout'       => 8,
            'ignore_errors' => true,
        ]]);
        $json = @file_get_contents($url, false, $ctx);
    }
    if (!$json) {
        return null;
    }
    $data = json_decode((string) $json, true);
    if (!is_array($data) || empty($data['sha'])) {
        return null;
    }
    return [
        'sha'     => substr((string) $data['sha'], 0, 7),
        'message' => (string) strtok((string) ($data['commit']['message'] ?? ''), "\n"),
        'date'    => (string) ($data['commit']['author']['date'] ?? ''),
    ];
}

/**
 * Validate and store an uploaded logo into /uploads.
 * @return array{0:bool,1:string} [ok, relative path | error message]
 */
function handle_logo_upload(array $file): array
{
    if (($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK) {
        return [false, 'Logo upload failed (error ' . (int) ($file['error'] ?? -1) . ').'];
    }
    if (($file['size'] ?? 0) > 2 * 1024 * 1024) {
        return [false, 'Logo is larger than 2 MB.'];
    }
    $ext     = strtolower(pathinfo((string) $file['name'], PATHINFO_EXTENSION));
    $allowed = ['png', 'jpg', 'jpeg', 'webp', 'gif', 'svg'];
    if (!in_array($ext, $allowed, true)) {
        return [false, 'Unsupported logo type. Use PNG, JPG, WebP, GIF or SVG.'];
    }
    $tmp = (string) $file['tmp_name'];
    if ($ext === 'svg') {
        $head = (string) @file_get_contents($tmp, false, null, 0, 2048);
        if (stripos($head, '<svg') === false) {
            return [false, 'That file does not look like a valid SVG.'];
        }
    } elseif (@getimagesize($tmp) === false) {
        return [false, 'That file is not a valid image.'];
    }
    $dir = dirname(__DIR__) . '/uploads';
    if (!is_dir($dir) && !@mkdir($dir, 0755, true) && !is_dir($dir)) {
        return [false, 'Could not create the uploads folder.'];
    }
    $name = 'logo-' . date('YmdHis') . '-' . bin2hex(random_bytes(3)) . '.' . $ext;
    if (!@move_uploaded_file($tmp, $dir . '/' . $name)) {
        return [false, 'Could not save the uploaded logo.'];
    }
    return [true, 'uploads/' . $name];
}

function deploy_log_tail(int $n = 12): array
{
    $file = __DIR__ . '/deploy.log';
    if (!is_file($file)) {
        return [];
    }
    $lines = @file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [];
    return array_slice($lines, -$n);
}

function deploy_log(string $msg): void
{
    $line = '[' . date('Y-m-d H:i:s') . '] ' . str_replace(["\r", "\n"], ' ', $msg) . "\n";
    @file_put_contents(__DIR__ . '/deploy.log', $line, FILE_APPEND | LOCK_EX);
}

/** @return array{0:bool,1:string} [success, message] */
function run_deploy(array $config): array
{
    if (($config['deploy_mode'] ?? 'webhook') === 'git') {
        if (!shell_available()) {
            return [false, 'shell_exec is disabled on this host. Use deploy_mode "webhook" instead.'];
        }
        $path = $config['git_path'] ?: dirname(__DIR__);
        if (!is_dir($path . '/.git')) {
            return [false, "No .git folder found in: $path"];
        }
        $out = (string) @shell_exec('cd ' . escapeshellarg($path) . ' 2>&1 && git pull 2>&1');
        $out = trim($out) ?: 'git produced no output.';
        $ok  = stripos($out, 'fatal') === false && stripos($out, 'error:') === false;
        return [$ok, $out];
    }

    // webhook mode
    $url = trim((string) ($config['deploy_hook_url'] ?? ''));
    if ($url === '' || !preg_match('~^https?://~i', $url)) {
        return [false, 'No valid deploy_hook_url is configured (see admin/config.local.php).'];
    }

    if (function_exists('curl_init')) {
        $ch = curl_init($url);
        curl_setopt_array($ch, [
            CURLOPT_POST           => true,
            CURLOPT_POSTFIELDS     => '',
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_FOLLOWLOCATION => true,
            CURLOPT_TIMEOUT        => 25,
            CURLOPT_HTTPHEADER     => ['User-Agent: Pasora-Admin-Deploy'],
        ]);
        $body = (string) curl_exec($ch);
        $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $err  = curl_error($ch);
        curl_close($ch);
        if ($err !== '') {
            return [false, "Request failed: $err"];
        }
    } else {
        $ctx = stream_context_create(['http' => [
            'method'        => 'POST',
            'header'        => "Content-Type: application/x-www-form-urlencoded\r\nUser-Agent: Pasora-Admin-Deploy\r\n",
            'content'       => '',
            'timeout'       => 25,
            'ignore_errors' => true,
        ]]);
        $body = @file_get_contents($url, false, $ctx);
        $code = 0;
        if (isset($http_response_header[0]) && preg_match('~\s(\d{3})\s~', $http_response_header[0], $m)) {
            $code = (int) $m[1];
        }
        if ($body === false) {
            return [false, 'Request to the deploy URL failed.'];
        }
    }

    $ok  = $code >= 200 && $code < 300;
    $msg = "Deploy webhook responded HTTP $code." . (trim((string) $body) !== '' ? ' ' . substr(trim((string) $body), 0, 300) : '');
    return [$ok, $msg];
}

