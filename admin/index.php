/* ──────────────────────────────────────────────────────────────
 *  ROUTING
 * ────────────────────────────────────────────────────────────── */
$action    = $_GET['action'] ?? '';
$needsSetup = empty($config['password_hash']);

/* Logout */
if ($action === 'logout') {
    $_SESSION = [];
    session_destroy();
    header('Location: index.php');
    exit;
}

/* ── First-run setup: create the admin password ───────────────── */
if ($needsSetup) {
    $err = '';
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        if (!csrf_ok()) {
            $err = 'Session expired — please try again.';
        } else {
            $p1 = (string) ($_POST['pw'] ?? '');
            $p2 = (string) ($_POST['pw2'] ?? '');
            if (strlen($p1) < 10) {
                $err = 'Use a password of at least 10 characters.';
            } elseif ($p1 !== $p2) {
                $err = 'The two passwords do not match.';
            } else {
                $config['password_hash'] = password_hash($p1, PASSWORD_DEFAULT);
                if (save_config($config, $configFile)) {
                    $_SESSION['authed'] = true;
                    session_regenerate_id(true);
                    deploy_log('Admin password created.');
                    header('Location: index.php');
                    exit;
                }
                $err = 'Could not write admin/config.local.php. Make the admin folder '
                     . 'writable, or create the file manually from config.example.php.';
            }
        }
    }
    page_top('Set up', $config['site_name']);
    echo '<div class="card"><h1>Create your admin password</h1>';
    echo '<p>This is the first run. Choose a password to protect the deploy panel. '
       . 'It is stored only as a one-way hash in <code>admin/config.local.php</code>.</p>';
    if ($err) { echo '<div class="note err">' . h($err) . '</div>'; }
    echo '<form method="post" action="index.php">';
    echo '<input type="hidden" name="csrf" value="' . h(csrf_token()) . '">';
    echo '<label for="pw">New password (min 10 characters)</label>';
    echo '<input id="pw" type="password" name="pw" autocomplete="new-password" required minlength="10">';
    echo '<label for="pw2">Confirm password</label>';
    echo '<input id="pw2" type="password" name="pw2" autocomplete="new-password" required minlength="10">';
    echo '<button type="submit">Create password &amp; sign in</button>';
    echo '</form></div>';
    echo '<p class="muted">Tip: set this immediately after your first deploy so the panel is never left open.</p>';
    page_bottom();
    exit;
}

/* ── Login ────────────────────────────────────────────────────── */
if (!is_authed()) {
    $err       = '';
    $lockUntil = (int) ($_SESSION['lock_until'] ?? 0);
    $locked    = $lockUntil > time();

    if ($_SERVER['REQUEST_METHOD'] === 'POST' && !$locked) {
        if (!csrf_ok()) {
            $err = 'Session expired — please try again.';
        } elseif (password_verify((string) ($_POST['pw'] ?? ''), (string) $config['password_hash'])) {
            $_SESSION['authed']     = true;
            $_SESSION['login_fails'] = 0;
            session_regenerate_id(true);
            header('Location: index.php');
            exit;
        } else {
            $_SESSION['login_fails'] = (int) ($_SESSION['login_fails'] ?? 0) + 1;
            if ($_SESSION['login_fails'] >= 5) {
                $_SESSION['lock_until']  = time() + (int) $config['lockout_seconds'];
                $_SESSION['login_fails'] = 0;
                $locked = true;
                deploy_log('Login locked after repeated failures.');
            }
            $err = 'Incorrect password.';
        }
    }

    page_top('Sign in', $config['site_name']);
    echo '<div class="card"><h1>Sign in</h1>';
    if ($locked) {
        $mins = (int) ceil(((int) $_SESSION['lock_until'] - time()) / 60);
        echo '<div class="note err">Too many attempts. Try again in about ' . $mins . ' minute(s).</div>';
    }
    if ($err && !$locked) { echo '<div class="note err">' . h($err) . '</div>'; }
    echo '<form method="post" action="index.php">';
    echo '<input type="hidden" name="csrf" value="' . h(csrf_token()) . '">';
    echo '<label for="pw">Admin password</label>';
    echo '<input id="pw" type="password" name="pw" autocomplete="current-password" required'
       . ($locked ? ' disabled' : '') . '>';
    echo '<button type="submit"' . ($locked ? ' disabled' : '') . '>Sign in</button>';
    echo '</form></div>';
    page_bottom();
    exit;
}

/* ── Authenticated: handle a deploy POST ──────────────────────── */
$flash = null;
if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['do'] ?? '') === 'deploy') {
    if (!csrf_ok()) {
        $flash = [false, 'Session expired — please try again.'];
    } else {
        [$ok, $msg] = run_deploy($config);
        deploy_log(($ok ? 'OK  ' : 'FAIL') . ' — ' . $msg);
        $flash = [$ok, $msg];
    }
}

/* ── Dashboard ────────────────────────────────────────────────── */
$commit = current_commit($config['git_path'] ?: dirname(__DIR__));
$mode   = $config['deploy_mode'] ?? 'webhook';
$ready  = $mode === 'git'
        ? (shell_available() && is_dir(($config['git_path'] ?: dirname(__DIR__)) . '/.git'))
        : (trim((string) $config['deploy_hook_url']) !== '');

page_top('Deploy', $config['site_name']);

echo '<div class="row" style="justify-content:space-between">';
echo '<h1 style="margin:0">Deploy</h1>';
echo '<form method="get" action="index.php" style="margin:0"><input type="hidden" name="action" value="logout">'
   . '<button class="ghost" type="submit">Sign out</button></form>';
echo '</div><p>Publish the latest code from GitHub to this server.</p>';

if ($flash) {
    echo '<div class="note ' . ($flash[0] ? 'ok' : 'err') . '">'
       . ($flash[0] ? '✓ Deploy triggered. ' : '✗ Deploy failed. ')
       . h($flash[1]) . '</div>';
}

echo '<div class="card"><h2>Status</h2>';
echo '<div class="kv"><span>Deploy method</span><span>' . h($mode) . '</span></div>';
echo '<div class="kv"><span>Configured</span><span>' . ($ready ? 'Yes' : 'No — see config.local.php') . '</span></div>';
echo '<div class="kv"><span>Current commit</span><span>' . ($commit ? h($commit) : '—') . '</span></div>';
echo '<div class="kv"><span>Server time</span><span>' . h(date('Y-m-d H:i:s')) . '</span></div>';
echo '</div>';

echo '<div class="card"><h2>Publish</h2>';
if (!$ready) {
    echo '<div class="note err">Deployment is not configured yet. Open '
       . '<code>admin/config.local.php</code> and set '
       . ($mode === 'git' ? 'a valid <code>git_path</code> with a <code>.git</code> folder, and enable SSH/git on your plan.'
                          : 'your <code>deploy_hook_url</code> (copy it from hPanel → Git → auto-deployment).')
       . '</div>';
}
echo '<p>Clicking Deploy ' . ($mode === 'git' ? 'runs <code>git pull</code> on the server.' : 'sends the deploy webhook so Hostinger pulls the latest commit.') . '</p>';
echo '<form method="post" action="index.php">';
echo '<input type="hidden" name="csrf" value="' . h(csrf_token()) . '">';
echo '<input type="hidden" name="do" value="deploy">';
echo '<button type="submit"' . ($ready ? '' : ' disabled') . '>Deploy now</button>';
echo '</form></div>';

$tail = deploy_log_tail();
echo '<div class="card"><h2>Recent activity</h2>';
if ($tail) {
    echo '<pre>' . h(implode("\n", $tail)) . '</pre>';
} else {
    echo '<p>No deploys logged yet.</p>';
}
echo '</div>';

page_bottom();
